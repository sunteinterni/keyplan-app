// Turns the FF&E Symbol Guideline (reference/symbol-guideline, exported from Claude Design) into code, so the plan,
// the item forms and the PDF use exactly the guideline's drawings. Usage: npm run symbols  (rewrites shared/glyph-data.ts)
import fs from 'node:fs';
import path from 'node:path';

const SRC = path.resolve('reference/symbol-guideline/Keyplan Symbol Guideline.dc.html');

if (process.argv[1] && path.resolve(process.argv[1]).endsWith(path.join('scripts', 'extract-symbols.ts'))) {
  const html = fs.readFileSync(SRC, 'utf8');
  const start = html.indexOf('const D = [');
  const end = html.indexOf('];', start);
  if (start < 0 || end < 0) throw new Error('symbol table not found in the guideline');
  // the table is plain array literals of strings: evaluate it on its own, nothing else from the file runs
  const table = new Function(`return ${html.slice(start + 'const D = '.length, end + 1)}`)() as [string, string, string, [string, string, string][]][];
  const cats = table.map(([prefix, th, en, items]) => ({
    prefix,
    th,
    en,
    items: items.map(([e, t, spec], i) => ({ code: `${prefix}-${String(i + 1).padStart(2, '0')}`, en: e, th: t, spec })),
  }));
  const n = cats.reduce((a, c) => a + c.items.length, 0);
  const ts = `// GENERATED by scripts/extract-symbols.ts from reference/symbol-guideline (FF&E Symbol Guideline) — do not edit by hand.
// Floor-plan symbols per material category on a 64 × 64 grid. Spec: shapes separated by ';' —
// r x,y,w,h[,rx] · c cx,cy,r · e cx,cy,rx,ry · l x1,y1,x2,y2 · otherwise SVG path data; prefix ~ = dashed, * = light fill (18 %).

export interface GlyphDef {
  code: string; // F-01 …
  en: string;
  th: string;
  spec: string;
}
export interface GlyphCategory {
  prefix: string;
  th: string;
  en: string;
  items: GlyphDef[];
}

/** ${n} symbols in ${cats.length} categories. */
export const GLYPH_CATEGORIES: GlyphCategory[] = ${JSON.stringify(cats, null, 2)};
`;
  fs.writeFileSync(path.resolve('shared/glyph-data.ts'), ts);
  console.log(`${n} symbols in ${cats.length} categories → shared/glyph-data.ts`);
}
