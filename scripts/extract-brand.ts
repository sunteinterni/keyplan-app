// Turns the official KEYPLAN SVGs in reference/brand into code, so the web app and the PDF draw the
// same logo and category icons without retyping or redrawing them.
// Usage: npm run brand   (rewrites shared/brand-assets.ts and web/public/brand/*.svg)
import fs from 'node:fs';
import path from 'node:path';

const SRC = path.resolve('reference/brand');
const read = (f: string) => fs.readFileSync(path.join(SRC, f), 'utf8').replace(/<metadata>[\s\S]*?<\/metadata>/g, '').replace(/\s*xmlns:c2pa="[^"]*"/g, '');
const attrs = (tag: string) => Object.fromEntries([...tag.matchAll(/([\w-]+)="([^"]*)"/g)].map((m) => [m[1], m[2]]));

export type MarkShape =
  | { t: 'rect'; x: number; y: number; w: number; h: number; rx: number; fill: string }
  | { t: 'circle'; cx: number; cy: number; r: number; fill: string }
  | { t: 'path'; d: string; stroke: string; sw: number };

/** Shapes of the mark (100 × 100) and the wordmark path with its placement, from the horizontal lockup. */
function logo() {
  const svg = read('logo/keyplan-horizontal-color.svg');
  const groups = [...svg.matchAll(/<g transform="translate\(([-\d.]+) ([-\d.]+)\) scale\(([-\d.]+)\)">([\s\S]*?)<\/g>/g)];
  if (groups.length !== 2) throw new Error('unexpected logo structure');
  const mark: MarkShape[] = [];
  for (const m of groups[0][4].matchAll(/<(rect|circle|path)\b([^>]*)>/g)) {
    const a = attrs(m[2]);
    if (m[1] === 'rect') mark.push({ t: 'rect', x: +a.x, y: +a.y, w: +a.width, h: +a.height, rx: +(a.rx ?? 0), fill: a.fill });
    else if (m[1] === 'circle') mark.push({ t: 'circle', cx: +a.cx, cy: +a.cy, r: +a.r, fill: a.fill });
    else mark.push({ t: 'path', d: a.d, stroke: a.stroke, sw: +a['stroke-width'] });
  }
  const viewW = Number(/viewBox="0 0 ([\d.]+) 100"/.exec(svg)?.[1]);
  const d = /<path d="([^"]+)"/.exec(groups[1][4])?.[1];
  if (!d || !viewW) throw new Error('wordmark not found');
  return { mark, wordmark: { d, x: +groups[1][1], y: +groups[1][2], scale: +groups[1][3], viewW } };
}

/** Category icons (48 × 48, stroked paths) keyed by file name. */
function icons() {
  const dir = path.join(SRC, 'icons/charcoal');
  const out: Record<string, string[]> = {};
  for (const f of fs.readdirSync(dir).filter((x) => x.endsWith('.svg')).sort()) {
    out[f.replace(/\.svg$/, '')] = [...read(`icons/charcoal/${f}`).matchAll(/<path d="([^"]+)"/g)].map((m) => m[1]);
  }
  return out;
}

if (process.argv[1] && path.resolve(process.argv[1]).endsWith(path.join('scripts', 'extract-brand.ts'))) {
  const { mark, wordmark } = logo();
  const ic = icons();
  const ts = `// GENERATED by scripts/extract-brand.ts from reference/brand — do not edit by hand (npm run brand).
// Official KEYPLAN logo geometry and category icons, shared by the web app (SVG) and the PDF (pdfkit).

export type MarkShape =
  | { t: 'rect'; x: number; y: number; w: number; h: number; rx: number; fill: string }
  | { t: 'circle'; cx: number; cy: number; r: number; fill: string }
  | { t: 'path'; d: string; stroke: string; sw: number };

/** The room-plan mark, drawn in a 100 × 100 box. */
export const MARK_SHAPES: MarkShape[] = ${JSON.stringify(mark, null, 2)};

/** "KEYPLAN" wordmark path, placed at (x, y) with scale inside a lockup ${wordmark.viewW} wide and 100 high (mark on the left). */
export const WORDMARK_PATH = ${JSON.stringify(wordmark, null, 2)};

/** Category icon paths (48 × 48, stroke 2.25, square caps), one entry per icon file. */
export const ICON_PATHS: Record<string, string[]> = ${JSON.stringify(ic, null, 2)};
`;
  fs.writeFileSync(path.resolve('shared/brand-assets.ts'), ts);
  // static files for the web app: logo, favicon and the canvas plan pattern, without the provenance metadata
  const pub = path.resolve('web/public/brand');
  fs.mkdirSync(pub, { recursive: true });
  for (const f of ['logo/keyplan-horizontal-color.svg', 'logo/keyplan-horizontal-tagline-color.svg', 'logo/keyplan-mark-color.svg', 'logo/keyplan-app-icon-canvas.svg', 'pattern/keyplan-pattern-plan-canvas.svg', 'pattern/keyplan-pattern-plan-furnished-canvas.svg']) {
    fs.writeFileSync(path.join(pub, path.basename(f)), read(f));
  }
  console.log(`mark ${mark.length} shapes · wordmark ${wordmark.d.length} chars · ${Object.keys(ic).length} icons → shared/brand-assets.ts, web/public/brand/`);
}
